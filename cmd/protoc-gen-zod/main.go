// protoc-gen-zod generates Zod schemas for the Connect/ProtoJSON wire format.
package main

import (
	"flag"
	"fmt"
	"path"
	"sort"
	"strconv"
	"strings"

	"google.golang.org/protobuf/compiler/protogen"
	"google.golang.org/protobuf/reflect/protoreflect"
	"google.golang.org/protobuf/types/pluginpb"
)

var stripPrefix string

func main() {
	flags := flag.NewFlagSet("protoc-gen-zod", flag.ContinueOnError)
	flags.StringVar(&stripPrefix, "strip_prefix", "", "proto path prefix to omit from output paths")
	protogen.Options{ParamFunc: flags.Set}.Run(func(plugin *protogen.Plugin) error {
		plugin.SupportedFeatures = uint64(pluginpb.CodeGeneratorResponse_FEATURE_PROTO3_OPTIONAL)
		exports := map[string][]string{}
		for _, file := range plugin.Files {
			if !file.Generate {
				continue
			}
			name := outputName(file.Desc.Path())
			g := plugin.NewGeneratedFile(name+".ts", "")
			g.P("// Code generated by protoc-gen-zod. DO NOT EDIT.")
			g.P("// Source: ", file.Desc.Path())
			g.P(`import { z } from "zod";`)
			imports := map[string]map[string]bool{}
			for _, message := range messages(file.Messages) {
				for _, field := range message.Fields {
					if field.Desc.IsMap() {
						field = field.Message.Fields[1]
					}
					var source, symbol string
					if field.Message != nil {
						source, symbol = field.Message.Desc.ParentFile().Path(), field.Message.GoIdent.GoName
					} else if field.Enum != nil {
						source, symbol = field.Enum.Desc.ParentFile().Path(), field.Enum.GoIdent.GoName
					}
					if source == "" || source == file.Desc.Path() {
						continue
					}
					dependency := plugin.FilesByPath[source]
					if dependency == nil || !dependency.Generate {
						return fmt.Errorf("%s: external type %s is not supported; include its proto in generation", field.Desc.FullName(), symbol)
					}
					if imports[source] == nil {
						imports[source] = map[string]bool{}
					}
					imports[source][symbol] = true
				}
			}
			for _, source := range sortedKeys(imports) {
				// Preserve proto directory structure, including cross-package imports.
				from := strings.Split(path.Dir(name), "/")
				to := strings.Split(outputName(source), "/")
				for len(from) > 0 && len(to) > 0 && from[0] == to[0] {
					from, to = from[1:], to[1:]
				}
				module := strings.Repeat("../", len(from)) + strings.Join(to, "/")
				if !strings.HasPrefix(module, ".") {
					module = "./" + module
				}
				var symbols []string
				for _, symbol := range sortedKeys(imports[source]) {
					symbols = append(symbols, symbol+"Schema", "type "+symbol)
				}
				g.P("import { ", strings.Join(symbols, ", "), " } from ", strconv.Quote(module), ";")
			}
			for _, enum := range enums(file) {
				var values []string
				for _, value := range enum.Values {
					values = append(values, strconv.Quote(string(value.Desc.Name())))
				}
				name := enum.GoIdent.GoName
				g.P("export const ", name, "Schema = z.union([z.enum([", strings.Join(values, ", "), "]), z.number().int().min(-2147483648).max(2147483647)]);")
				g.P("export type ", name, " = z.infer<typeof ", name, "Schema>;")
			}
			for _, message := range messages(file.Messages) {
				name := message.GoIdent.GoName
				if len(message.Fields) == 0 {
					g.P("export type ", name, " = Record<string, never>;")
				} else {
					g.P("export type ", name, " = {")
					for _, field := range message.Fields {
						_, typ, err := fieldType(field)
						if err != nil {
							return err
						}
						g.P(strconv.Quote(field.Desc.JSONName()), "?: ", typ, " | null;")
					}
					g.P("};")
				}
				g.P("export const ", name, "Schema = z.object({")
				for _, field := range message.Fields {
					schema, typ, err := fieldType(field)
					if err != nil {
						continue
					}
					// Lazy getters support forward references and recursive messages.
					g.P("get ", strconv.Quote(field.Desc.JSONName()), "(): z.ZodOptional<z.ZodNullable<z.ZodType<", typ, ">>> { return ", schema, ".nullish(); },")
				}
				g.P("})")
				for _, oneof := range message.Oneofs {
					if oneof.Desc.IsSynthetic() {
						continue
					}
					var fields []string
					for _, field := range oneof.Fields {
						fields = append(fields, "value["+strconv.Quote(field.Desc.JSONName())+"]")
					}
					g.P(".refine((value) => [", strings.Join(fields, ", "), "].filter((field) => field != null).length <= 1, { message: ", strconv.Quote("Only one field in "+string(oneof.Desc.Name())+" may be set"), " })")
				}
				g.P(";")
			}
			exports[path.Dir(name)] = append(exports[path.Dir(name)], path.Base(name))
		}
		for _, directory := range sortedKeys(exports) {
			sort.Strings(exports[directory])
			index := plugin.NewGeneratedFile(path.Join(directory, "index.ts"), "")
			index.P("// Code generated by protoc-gen-zod. DO NOT EDIT.")
			for _, name := range exports[directory] {
				index.P("export * from ", strconv.Quote("./"+name), ";")
			}
		}
		return nil
	})
}

func outputName(source string) string {
	source = strings.TrimPrefix(source, stripPrefix)
	base := strings.TrimSuffix(path.Base(source), ".proto")
	var parts []string
	for _, part := range strings.Split(base, "_") {
		parts = append(parts, strings.ToUpper(part[:1])+part[1:])
	}
	return path.Join(path.Dir(source), strings.Join(parts, "")+"Schema")
}

func sortedKeys[V any](values map[string]V) []string {
	keys := make([]string, 0, len(values))
	for key := range values {
		keys = append(keys, key)
	}
	sort.Strings(keys)
	return keys
}

func messages(input []*protogen.Message) []*protogen.Message {
	var result []*protogen.Message
	for _, message := range input {
		if message.Desc.IsMapEntry() {
			continue
		}
		result = append(result, message)
		result = append(result, messages(message.Messages)...)
	}
	return result
}

func enums(file *protogen.File) []*protogen.Enum {
	result := append([]*protogen.Enum{}, file.Enums...)
	for _, message := range messages(file.Messages) {
		result = append(result, message.Enums...)
	}
	return result
}

func fieldType(field *protogen.Field) (schema, typ string, err error) {
	if field.Desc.IsMap() {
		valueSchema, valueType, err := fieldType(field.Message.Fields[1])
		return "z.record(z.string(), " + valueSchema + ")", "Record<string, " + valueType + ">", err
	}
	switch field.Desc.Kind() {
	case protoreflect.StringKind, protoreflect.BytesKind:
		schema, typ = "z.string()", "string" // bytes are base64 in ProtoJSON.
	case protoreflect.BoolKind:
		schema, typ = "z.boolean()", "boolean"
	case protoreflect.Int32Kind, protoreflect.Sint32Kind, protoreflect.Sfixed32Kind:
		schema, typ = "z.number().int().min(-2147483648).max(2147483647)", "number"
	case protoreflect.Uint32Kind, protoreflect.Fixed32Kind:
		schema, typ = "z.number().int().min(0).max(4294967295)", "number"
	case protoreflect.Int64Kind, protoreflect.Sint64Kind, protoreflect.Sfixed64Kind:
		schema, typ = `z.string().regex(/^-?\d+$/)`, "string"
	case protoreflect.Uint64Kind, protoreflect.Fixed64Kind:
		schema, typ = `z.string().regex(/^\d+$/)`, "string"
	case protoreflect.FloatKind, protoreflect.DoubleKind:
		schema, typ = `z.union([z.number(), z.enum(["NaN", "Infinity", "-Infinity"])])`, `number | "NaN" | "Infinity" | "-Infinity"`
	case protoreflect.EnumKind:
		schema, typ = field.Enum.GoIdent.GoName+"Schema", field.Enum.GoIdent.GoName
	case protoreflect.MessageKind:
		schema, typ = field.Message.GoIdent.GoName+"Schema", field.Message.GoIdent.GoName
	default:
		return "", "", fmt.Errorf("%s: unsupported kind %s", field.Desc.FullName(), field.Desc.Kind())
	}
	if field.Desc.IsList() {
		schema, typ = "z.array("+schema+")", "Array<"+typ+">"
	}
	return schema, typ, nil
}
